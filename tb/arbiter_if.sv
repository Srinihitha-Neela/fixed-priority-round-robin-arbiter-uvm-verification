//=========================================================
// File: arbiter_if.sv
//
// Common interface used for BOTH:
//   1. Fixed-priority arbiter
//   2. Round-robin arbiter
//
// req and grant are used by both DUTs.
//
// clk and reset are required by the round-robin arbiter.
// They remain present for the fixed-priority environment
// so that the same UVM driver and monitor can be reused.
//
// SystemVerilog Assertions (SVA) are included directly
// in the interface so that protocol/property checking is
// centralized for both arbiters.
//=========================================================

interface arbiter_if(input logic clk);

    //=====================================================
    // INTERFACE SIGNALS
    //=====================================================

    // Reset signal
    //
    // Used by the round-robin arbiter.
    // The fixed-priority arbiter is combinational, but
    // reset remains part of the common interface.
    logic reset;


    // Request vector
    //
    // req[0] -> Requester 0
    // req[1] -> Requester 1
    // req[2] -> Requester 2
    // req[3] -> Requester 3
    logic [3:0] req;


    // Grant vector generated by the DUT.
    //
    // Legal grant values:
    //
    // 0000 -> No requester granted
    // 0001 -> Requester 0 granted
    // 0010 -> Requester 1 granted
    // 0100 -> Requester 2 granted
    // 1000 -> Requester 3 granted
    logic [3:0] grant;


    //=====================================================
    // DUT MODE SELECTION
    //=====================================================

    // Set by the top-level testbench.
    //
    // 0 -> Fixed-priority arbiter
    // 1 -> Round-robin arbiter
    //
    // tb_fixed.sv must set:
    //     arb_if.is_rr = 1'b0;
    //
    // tb_round_robin.sv must set:
    //     arb_if.is_rr = 1'b1;
    bit is_rr;


    //=====================================================
    // COMMON ASSERTIONS
    //=====================================================
    //
    // These assertions apply to BOTH arbiters.
    //=====================================================


    // ----------------------------------------------------
    // Grant must be known and zero-hot/one-hot.
    //
    // $isunknown() detects X/Z values.
    //
    // $onehot0() allows:
    //   0000
    //   0001
    //   0010
    //   0100
    //   1000
    //
    // but rejects multi-hot values such as:
    //   0011
    //   0101
    //   1100
    // ----------------------------------------------------

    a_grant_onehot0 : assert property (
        @(posedge clk)
        disable iff (reset)
        (!$isunknown(grant) && $onehot0(grant))
    )
    else
        $error(
            "SVA: grant is unknown or not one-hot/zero-hot: grant=%b",
            grant
        );



endinterface
